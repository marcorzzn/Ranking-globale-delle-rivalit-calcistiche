export type ConfederationId = 'UEFA' | 'CONMEBOL' | 'CONCACAF' | 'CAF' | 'AFC' | 'OFC';
export type LeagueTier = 1 | 2 | 3; // 1 = Serie A / 1st Div, 2 = Serie B / 2nd Div, 3 = Serie C / 3rd Div

export type CupTournamentId =
  | 'FIFA_CWC' // FIFA Club World Cup (Quadrennial / Cyclic)
  | 'UCL' // UEFA Champions League
  | 'UEL' // UEFA Europa League
  | 'UECL' // UEFA Conference League
  | 'LIBERTADORES' // CONMEBOL Copa Libertadores
  | 'SUDAMERICANA' // CONMEBOL Copa Sudamericana
  | 'CONCACAF_CC' // CONCACAF Champions Cup
  | 'LEAGUES_CUP' // Leagues Cup (MLS / Liga MX)
  | 'CAF_CL' // CAF Champions League
  | 'AFC_ELITE' // AFC Champions League Elite
  | 'OFC_CL' // OFC Champions League
  | 'DOMESTIC_CUP'; // Coppa Nazionale (Coppa Italia, FA Cup, Copa del Rey, DFB-Pokal, Copa do Brasil...)

export interface CupTournamentMeta {
  id: CupTournamentId;
  name: { it: string; en: string };
  shortLabel: string;
  confederation: ConfederationId | 'FIFA' | 'GLOBAL';
  cadence: 'annual' | 'quadrennial';
  color: string;
  zonePolygon: Array<[number, number]>; // Geographic jurisdiction boundary for map overlay
}

export interface ConfederationMeta {
  id: ConfederationId;
  name: string;
  fullTitle: { it: string; en: string };
  color: string;
  hqCity: string;
  center: [number, number];
  zoom: number;
  boundaryPolygon: Array<[number, number]>;
}

export interface WorldClubEntry {
  id: string;
  name: string;
  shortCode: string;
  wikidataId: string;
  confederation: ConfederationId;
  country: { it: string; en: string };
  tier: LeagueTier; // 1 = Serie A/Top, 2 = Serie B/2nd, 3 = Serie C/3rd
  leagueName: string;
  optaLeagueRank: number;
  stadiumName: string;
  city: string;
  lat: number;
  lng: number;
  capacity: number;
  primaryColor: string;
  secondaryColor: string;
  pattern: 'stripes' | 'halves' | 'diagonal' | 'solid' | 'hoops';
  cups: CupTournamentId[];
  titlesCount?: number;
}

